package Level1PracticePrograms;

public class KilometerToMIles {
    public static void main(String[] args) {
        double kilometers = 10.8; // Example distance in kilometers
        double miles = kilometers * 1.6; // Conversion factor from kilometers to miles
        
        System.out.printf("%.2f kilometers is equal to %.2f miles.%n", kilometers, miles);
    }
}
